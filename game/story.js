function judge(s) {
  const v = s.v;
  if (v.cover || v.distance || v.watch >= 6 || v.harm >= 9) return 'X_caught';
  if (v.heardHer && v.harm <= 2 && v.kind >= 8 && (v.notebook || v.owned) && !v.publicAsk && !v.joined) return 'E_true';
  if (v.heardHer && v.harm <= 5) return 'E_good';
  if (v.lecture || v.advice || v.decided) return 'E_blade';
  return 'E_miss';
}
function bondRoute(s) {
  const b = (s.v.kind || 0) - (s.v.harm || 0);
  if (b >= 2) return 'N_4open';
  if (b >= -1) return 'N_4crack';
  return 'N_4cold';
}

