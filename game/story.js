/* 点数 → タイプ判定（比率 0〜1） */
function classify(e, u, a) {
  if (e < 0.35 && u < 0.40) return 'indifferent';              // どちらも低い
  if (u - e >= 0.08 && u >= 0.45) return 'knowledge';          // 知識が気持ちより先行
  if (a >= 0.45 && e >= 0.50) return 'empathy';                // 感じて、動ける
  if (e >= 0.35 && a < 0.45) return 'bystander';               // 感じるが、動けない
  return e >= 0.50 ? 'empathy' : 'indifferent';
}

